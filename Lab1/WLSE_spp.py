#!/usr/bin/env python3
"""Runnable teaching WLS example. All paths are relative to this package by default.

Historical mode reproduces the supplied 186-epoch example. GPS mode accepts
the GPS-only matrices generated by rinex2csv.m. Neither needs benchmark truth.
"""
import argparse
import csv
import json
import math
from pathlib import Path

import numpy as np
from tools.legacy_solver import (weighted_least_squares_solution,
                                 ecef_to_lla, ecef_to_enu)

ROOT = Path(__file__).resolve().parent
HEADER = ['gps_week', 'gps_tow_s', 'x_ecef_m', 'y_ecef_m', 'z_ecef_m']


def read_inputs(folder):
    names = ['pseudoranges_meas', 'satellite_clock_bias', 'ionospheric_delay',
             'tropospheric_delay', 'satellite_positions']
    arrays = {name: np.loadtxt(folder / (name + '.csv'), delimiter=',', ndmin=2)
              for name in names}
    shape = arrays['pseudoranges_meas'].shape
    for name in names[1:4]:
        if arrays[name].shape != shape:
            raise ValueError(f'{name}: dimensions do not match pseudoranges {shape}')
    if arrays['satellite_positions'].shape != (shape[0], 3 * shape[1]):
        raise ValueError('satellite_positions must have 3 columns per epoch')
    with (folder / 'epochs.csv').open(encoding='utf-8-sig', newline='') as stream:
        epochs = [(int(r['gps_week']), float(r['gps_tow_s'])) for r in csv.DictReader(stream)]
    if len(epochs) != shape[1]:
        raise ValueError('epochs.csv count differs from measurement columns')
    keys = [(w, round(t, 1)) for w, t in epochs]
    if keys != sorted(set(keys)):
        raise ValueError('Epochs are unsorted or duplicate on the submission 0.1 s grid')
    if any(w < 0 or not math.isfinite(t) or not 0 <= t < 604800 for w, t in epochs):
        raise ValueError('Invalid GPS week/time')
    arrays['group_delay'] = (np.loadtxt(folder / 'group_delay.csv', delimiter=',', ndmin=2)
                             if (folder / 'group_delay.csv').exists() else np.zeros(shape))
    if arrays['group_delay'].shape != shape:
        raise ValueError('group_delay dimensions do not match')
    return arrays, epochs


def gps_solution(sp, pr, clk, ion, trp, tgd, seed):
    """One GPS clock, weighted LS, Sagnac correction; do not reuse a failed epoch."""
    x = np.r_[seed.copy(), 0.0]
    corrected = pr + clk - ion - trp - tgd
    for _ in range(30):
        delta = sp - x[:3]
        ranges = np.linalg.norm(delta, axis=1)
        if np.any(ranges <= 0):
            raise ValueError('Zero range')
        H = np.column_stack((-delta / ranges[:, None], np.ones(len(sp))))
        sagnac = 7.2921151467e-5 / 299792458.0 * (sp[:, 0]*x[1] - sp[:, 1]*x[0])
        if np.linalg.norm(x[:3]) > 6e6:
            lat, lon, _ = ecef_to_lla(*x[:3])
            phi, lam = np.radians([lat, lon])
            up = np.array([np.cos(phi)*np.cos(lam), np.cos(phi)*np.sin(lam), np.sin(phi)])
            sine = delta @ up / ranges
            weights = np.maximum(sine, 0.05)**2
        else:
            weights = np.ones(len(sp))
        scale = np.sqrt(weights)
        dx, _, rank, _ = np.linalg.lstsq(H*scale[:, None],
                                        (corrected-ranges-sagnac-x[3])*scale, rcond=None)
        if rank < 4:
            raise ValueError('Insufficient geometry')
        x += dx
        if np.linalg.norm(dx) < 1e-4:
            if np.isfinite(x).all() and 6.30e6 < np.linalg.norm(x[:3]) < 6.42e6:
                return x[:3], x[3]
            break
    raise ValueError('GPS WLS did not converge to a surface position')


def run(arrays, epochs, mode):
    rows, rejected = [], []
    seed = np.zeros(3)
    for i, (week, tow) in enumerate(epochs):
        sp = arrays['satellite_positions'][:, 3*i:3*i+3]
        vector = [arrays[n][:, i] for n in ['pseudoranges_meas', 'satellite_clock_bias',
                                           'ionospheric_delay', 'tropospheric_delay', 'group_delay']]
        mask = np.isfinite(sp).all(axis=1)
        for v in vector:
            mask &= np.isfinite(v)
        if mask.sum() < 4:
            rejected.append((week, tow, 'fewer than 4 usable GPS/input measurements'))
            continue
        pr, clk, ion, trp, tgd = [v[mask] for v in vector]
        try:
            if mode == 'historical':
                pos, bias = weighted_least_squares_solution(sp[mask], seed.copy(), pr, clk, ion, trp)
                if not np.isfinite(pos).all() or not 6.30e6 < np.linalg.norm(pos) < 6.42e6:
                    raise ValueError('Invalid historical solution')
            else:
                pos, bias = gps_solution(sp[mask], pr, clk, ion, trp, tgd, seed)
        except (ValueError, np.linalg.LinAlgError, FloatingPointError) as exc:
            rejected.append((week, tow, str(exc)))
            continue
        seed = pos.copy()
        rows.append({'gps_week': week, 'gps_tow_s': tow, 'position': pos.copy(),
                     'clock_bias_m': float(bias), 'used_measurements': int(mask.sum())})
    if not rows:
        raise ValueError('No valid solution was produced')
    return rows, rejected


def reference_metrics(rows, reference, epochs):
    """The provided receiver CSV is centimetres and milliseconds, not ground truth."""
    if len({w for w, _ in epochs}) != 1:
        raise ValueError('Receiver CSV has no GPS week; use a single-week dataset')
    reference_rows = {}
    with reference.open(encoding='utf-8-sig', newline='') as stream:
        for r in csv.DictReader(stream):
            if int(r.get('invalidEcef', '0')):
                continue
            key = round(float(r['iTOW']) / 1000, 1)
            if key in reference_rows:
                raise ValueError('Duplicate receiver reference time')
            reference_rows[key] = np.array([float(r[k])/100 for k in ['ecefX','ecefY','ecefZ']])
    reference_first = next(iter(reference_rows.values()))
    residuals = []
    for r in rows:
        ref = reference_rows.get(round(r['gps_tow_s'], 1))
        if ref is not None:
            # Same fixed local frame as the original 2025 numerical example.
            residuals.append(ecef_to_enu(*r['position'], *reference_first)
                             - ecef_to_enu(*ref, *reference_first))
    if not residuals:
        raise ValueError('No matching receiver reference epochs')
    err = np.array(residuals)
    return {'reference': 'receiver standalone solution, NOT ground truth',
            'matched_epochs': len(err),
            'rmse_2d_m': float(np.sqrt(np.mean(np.sum(err[:, :2]**2, axis=1)))),
            'rmse_3d_m': float(np.sqrt(np.mean(np.sum(err**2, axis=1)))),
            'p95_2d_m': float(np.percentile(np.linalg.norm(err[:, :2], axis=1), 95))}


def write_results(folder, filename, rows, rejected, epochs, mode, reference=None):
    folder.mkdir(parents=True, exist_ok=True)
    with (folder / filename).open('w', encoding='utf-8', newline='') as stream:
        writer = csv.writer(stream)
        writer.writerow(HEADER)
        for r in rows:
            writer.writerow([r['gps_week'], f"{r['gps_tow_s']:.1f}",
                             *[f'{v:.3f}' for v in r['position']]])
    with (folder / 'solution_details.csv').open('w', encoding='utf-8', newline='') as stream:
        writer = csv.writer(stream)
        writer.writerow(HEADER + ['clock_bias_m', 'used_measurements'])
        for r in rows:
            writer.writerow([r['gps_week'], f"{r['gps_tow_s']:.6f}", *r['position'],
                             r['clock_bias_m'], r['used_measurements']])
    with (folder / 'omitted_epochs.csv').open('w', encoding='utf-8', newline='') as stream:
        writer = csv.writer(stream)
        writer.writerow(['gps_week', 'gps_tow_s', 'reason'])
        writer.writerows(rejected)
    report = {'mode': mode, 'input_epochs': len(epochs), 'solved_epochs': len(rows),
              'omitted_epochs': len(rejected), 'coverage_percent': 100*len(rows)/len(epochs),
              'no_ground_truth_used_for_positioning': True,
              'time_grid': 'Actual OBS GPST rounded to 0.1 s only in submission CSV'}
    if reference:
        report['receiver_comparison'] = reference_metrics(rows, reference, epochs)
    (folder / 'summary.json').write_text(json.dumps(report, indent=2, allow_nan=False)+'\n', encoding='utf-8')
    return report


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--input-dir', type=Path, default=ROOT/'example')
    parser.add_argument('--output-dir', type=Path, default=ROOT/'outputs/example')
    parser.add_argument('--submission', default='G01_owndata.csv')
    parser.add_argument('--mode', choices=['historical', 'gps'], default='historical')
    parser.add_argument('--reference', type=Path, help='Optional receiver reference; never needed for a solution')
    args = parser.parse_args()
    if Path(args.submission).name != args.submission or not args.submission.endswith('.csv'):
        parser.error('--submission must be a CSV filename, not a path')
    if args.mode == 'historical' and args.input_dir.resolve() != (ROOT/'example').resolve():
        parser.error('Historical mode is only for the included 186-epoch dataset; use --mode gps for new GPS inputs')
    arrays, epochs = read_inputs(args.input_dir)
    rows, rejected = run(arrays, epochs, args.mode)
    report = write_results(args.output_dir, args.submission, rows, rejected, epochs, args.mode, args.reference)
    print(json.dumps(report, ensure_ascii=True, indent=2))
    print('Saved:', args.output_dir / args.submission)


if __name__ == '__main__':
    main()
